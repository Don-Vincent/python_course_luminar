# Identifiers
# ==============
# A user-defined sequence of characters used as a unique name to label and reference specific elements within a program
# like variable names, function names, class names etc are all examples of identifiers in python.

# Rules
# ==============
# Can use letters, digits (0-9), and underscores (_) in identifiers
# Always start an identifier with a letter (a-z, A-Z) or an underscore (_)
# Cannot use reserved keywords as identifiers
# Special characters like @, $, and % are not allowed in identifiers
# Python is case sensitive

# Data types
# ==============
# integer int(), float float(), string str(), boolean bool(), list list(), tuple tuple(), set set(), dictionary dict()
# name = "John"
# age = 25
# weight = 70.5
# alive = True

